"""## Problem 2.a: Deep Fully Connected Neural Network (10 Hidden Layers)

We configure a deeper network containing 10 hidden layers, using ReLU activation functions, maintaining comparable sizes to Problem 1.b.
"""

class DeepMLP(nn.Module):
    def __init__(self, input_size, num_classes=10):
        super(DeepMLP, self).__init__()
        # 10 hidden layers
        self.layers = nn.ModuleList([
            nn.Linear(input_size, 512),
            nn.Linear(512, 256),
            nn.Linear(256, 256),
            nn.Linear(256, 128),
            nn.Linear(128, 128),
            nn.Linear(128, 128),
            nn.Linear(128, 128),
            nn.Linear(128, 128),
            nn.Linear(128, 128),
            nn.Linear(128, 128)
        ])
        self.relu = nn.ReLU()
        self.out_layer = nn.Linear(128, num_classes)

    def forward(self, x):
        out = x.view(x.size(0), -1)
        for layer in self.layers:
            out = self.relu(layer(out))
        out = self.out_layer(out)
        return out

