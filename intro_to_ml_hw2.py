def compute_cost(X, Y, theta, lambda_param=0):
    predictions = X.dot(theta)
    errors = np.subtract(predictions, Y)
    sqrErrors = np.square(errors)
    # Regularization term for L2 (Ridge) regression, excludes theta[0] (intercept)
    regularization_term = (lambda_param / (2 * X.shape[0])) * np.sum(np.square(theta[1:]))
    J = (1 / (2 * X.shape[0])) * np.sum(sqrErrors) + regularization_term
    return J

def gradient_descent(X, y, theta_initial, alpha, iterations, lambda_param=0):
    theta = theta_initial.copy() # Use a copy to avoid modifying initial_theta directly
    cost_history = np.zeros(iterations)

    m_local = X.shape[0] # Use X.shape[0] for m to be general for train/validation sets

    for i in range(iterations):
        predictions = X.dot(theta)
        errors = np.subtract(predictions, y)

        # Gradient for theta[0] (intercept) - no regularization
        gradient_theta0 = (alpha / m_local) * np.sum(errors)

        # Gradient for theta[1:] (other features) - with L2 regularization
        gradient_others = (alpha / m_local) * X[:, 1:].transpose().dot(errors) + (alpha * lambda_param / m_local) * theta[1:]

        # Update theta
        theta[0] -= gradient_theta0
        theta[1:] -= gradient_others

        cost_history[i] = compute_cost(X, y, theta, lambda_param) # compute_cost now uses X.shape[0]

    return theta, cost_history

