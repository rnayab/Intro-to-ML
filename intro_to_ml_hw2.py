"""### L2 Regularization (Ridge Regression)

Regularization is a technique used to prevent overfitting in machine learning models by adding a penalty to the loss function. L2 regularization, also known as Ridge Regression, adds a penalty proportional to the square of the magnitude of the coefficients (`theta` values).

The modified cost function for L2 regularization is:

$$ J(\theta) = \frac{1}{2m} \sum_{i=1}^{m} (h_\theta(x^{(i)}) - y^{(i)})^2 + \frac{\lambda}{2m} \sum_{j=1}^{n} \theta_j^2 $$

Where:
- $h_\theta(x^{(i)})$ is the predicted value for the $i$-th example.
- $y^{(i)}$ is the actual value for the $i$-th example.
- $m$ is the number of training examples.
- $\lambda$ (lambda) is the regularization parameter, controlling the strength of the penalty.
- $\theta_j$ are the model parameters (coefficients), excluding the intercept ($\theta_0$).

A larger $\lambda$ value increases the penalty, forcing the coefficients to be smaller and reducing the model's complexity. A smaller $\lambda$ reduces the penalty, making the model more flexible. The choice of $\lambda$ is crucial and often determined through cross-validation.

For the following experiments, we will use a `lambda_param` of `0.1`.
"""

