import pandas as pd
import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import mean_squared_error, r2_score, accuracy_score, precision_score, recall_score, f1_score, confusion_matrix
import matplotlib.pyplot as plt
import seaborn as sns

# Set random seed for reproducibility
torch.manual_seed(42)
np.random.seed(42)

# URLs to the datasets
housing_url = 'https://raw.githubusercontent.com/HamedTabkhi/Intro-to-ML/main/Dataset/Housing.csv'
cancer_url = 'https://raw.githubusercontent.com/HamedTabkhi/Intro-to-ML/main/Dataset/Cancer.csv'

# Load datasets
housing_df = pd.read_csv(housing_url)
cancer_df = pd.read_csv(cancer_url)

print("Housing Dataset Shape:", housing_df.shape)
print("Cancer Dataset Shape:", cancer_df.shape)

print("Housing Data Preview:")
display(housing_df.head())

print("\nCancer Data Preview:")
display(cancer_df.head())

"""## Problem 1: Housing Price Prediction

### 1. Data Preprocessing for Housing Dataset
"""

# Map binary categorical features
binary_cols = ['mainroad', 'guestroom', 'basement', 'hotwaterheating', 'airconditioning', 'prefarea']
housing_prep = housing_df.copy()
for col in binary_cols:
    housing_prep[col] = housing_prep[col].map({'yes': 1, 'no': 0})

# One-hot encode furnishingstatus
housing_prep = pd.get_dummies(housing_prep, columns=['furnishingstatus'], drop_first=True)

# Separate features and target
X_h = housing_prep.drop(columns=['price']).values.astype(np.float32)
y_h = housing_prep['price'].values.astype(np.float32).reshape(-1, 1)

# Train-test split (80% train, 20% test)
X_train_h, X_test_h, y_train_h, y_test_h = train_test_split(X_h, y_h, test_size=0.2, random_state=42)

# Feature and Target standardization
scaler_X_h = StandardScaler()
scaler_y_h = StandardScaler()

X_train_h_scaled = scaler_X_h.fit_transform(X_train_h)
X_test_h_scaled = scaler_X_h.transform(X_test_h)

y_train_h_scaled = scaler_y_h.fit_transform(y_train_h)
y_test_h_scaled = scaler_y_h.transform(y_test_h)

# Convert to PyTorch tensors
X_train_h_tensor = torch.tensor(X_train_h_scaled, dtype=torch.float32)
y_train_h_tensor = torch.tensor(y_train_h_scaled, dtype=torch.float32)
X_test_h_tensor = torch.tensor(X_test_h_scaled, dtype=torch.float32)
y_test_h_tensor = torch.tensor(y_test_h_scaled, dtype=torch.float32)

print("Preprocessed Housing training features shape:", X_train_h_tensor.shape)
print("Preprocessed Housing training targets shape:", y_train_h_tensor.shape)

"""### 2. Neural Network Model Development, Training, and Evaluation"""

class HousingNet(nn.Module):
    def __init__(self, input_dim):
        super(HousingNet, self).__init__()
        self.network = nn.Sequential(
            nn.Linear(input_dim, 64),
            nn.ReLU(),
            nn.Linear(64, 32),
            nn.ReLU(),
            nn.Linear(32, 1)
        )

    def forward(self, x):
        return self.network(x)

# Initialize model, optimizer, loss function, and data loaders
input_dim_h = X_train_h_tensor.shape[1]
model_h = HousingNet(input_dim_h)
criterion_h = nn.MSELoss()
optimizer_h = optim.Adam(model_h.parameters(), lr=0.01)

# Hyperparameters
epochs_h = 300
batch_size_h = 32

train_losses_h = []
val_losses_h = []

# Training Loop
for epoch in range(epochs_h):
    model_h.train()
    permutation = torch.randperm(X_train_h_tensor.size()[0])
    epoch_loss = 0

    for i in range(0, X_train_h_tensor.size()[0], batch_size_h):
        indices = permutation[i:i+batch_size_h]
        batch_x, batch_y = X_train_h_tensor[indices], y_train_h_tensor[indices]

        optimizer_h.zero_grad()
        outputs = model_h(batch_x)
        loss = criterion_h(outputs, batch_y)
        loss.backward()
        optimizer_h.step()

        epoch_loss += loss.item() * batch_x.size(0)

    epoch_loss /= X_train_h_tensor.size(0)
    train_losses_h.append(epoch_loss)

    # Validation (using the test set as validation dataset during training)
    model_h.eval()
    with torch.no_grad():
        val_outputs = model_h(X_test_h_tensor)
        val_loss = criterion_h(val_outputs, y_test_h_tensor).item()
        val_losses_h.append(val_loss)

# Plots and Evaluation
plt.figure(figsize=(10, 6))
plt.plot(train_losses_h, label='Train Loss')
plt.plot(val_losses_h, label='Validation Loss')
plt.xlabel('Epochs')
plt.ylabel('Loss (MSE)')
plt.title('Housing Model Training & Validation Loss Over Epochs')
plt.legend()
plt.grid(True)
plt.show()

# Performance metrics on test data
model_h.eval()
with torch.no_grad():
    predictions_scaled = model_h(X_test_h_tensor).numpy()

# Inverse scale predictions and ground truth back to raw pricing scales
predictions = scaler_y_h.inverse_transform(predictions_scaled)
y_test_h_raw = scaler_y_h.inverse_transform(y_test_h_tensor.numpy())

mse_h = mean_squared_error(y_test_h_raw, predictions)
rmse_h = np.sqrt(mse_h)
r2_h = r2_score(y_test_h_raw, predictions)

print("\n--- Housing Regression Performance Metrics ---")
print(f"Mean Squared Error (MSE): {mse_h:.4f}")
print(f"Root Mean Squared Error (RMSE): {rmse_h:.4f}")
print(f"R² Score: {r2_h:.4f}")

"""### 3. Comparison with Linear Regression and Support Vector Regression (SVR)"""

from sklearn.linear_model import LinearRegression
from sklearn.svm import SVR

# 1. Linear Regression
lr_model = LinearRegression()
lr_model.fit(X_train_h_scaled, y_train_h_scaled.ravel())

lr_preds_scaled = lr_model.predict(X_test_h_scaled).reshape(-1, 1)
lr_preds = scaler_y_h.inverse_transform(lr_preds_scaled)

mse_lr = mean_squared_error(y_test_h_raw, lr_preds)
rmse_lr = np.sqrt(mse_lr)
r2_lr = r2_score(y_test_h_raw, lr_preds)

# 2. Support Vector Regression (SVR)
# We use an RBF kernel which is typical for non-linear regression
svr_model = SVR(kernel='rbf', C=1.0, epsilon=0.1)
svr_model.fit(X_train_h_scaled, y_train_h_scaled.ravel())

svr_preds_scaled = svr_model.predict(X_test_h_scaled).reshape(-1, 1)
svr_preds = scaler_y_h.inverse_transform(svr_preds_scaled)

mse_svr = mean_squared_error(y_test_h_raw, svr_preds)
rmse_svr = np.sqrt(mse_svr)
r2_svr = r2_score(y_test_h_raw, svr_preds)

# Compare results in a DataFrame
comparison_df = pd.DataFrame({
    'Metric': ['MSE', 'RMSE', 'R² Score'],
    'FCNN (PyTorch)': [mse_h, rmse_h, r2_h],
    'Linear Regression': [mse_lr, rmse_lr, r2_lr],
    'SVR (RBF Kernel)': [mse_svr, rmse_svr, r2_svr]
})

display(comparison_df)

"""## Problem 2: Breast Cancer Classification

### 1. Data Preprocessing for Breast Cancer Dataset
"""

# Drop unnecessary columns if they exist
cancer_prep = cancer_df.drop(columns=['id', 'Unnamed: 32'], errors='ignore')

# Map target variable (M = 1, B = 0)
cancer_prep['diagnosis'] = cancer_prep['diagnosis'].map({'M': 1, 'B': 0})

# Separate features and target
X_c = cancer_prep.drop(columns=['diagnosis']).values.astype(np.float32)
y_c = cancer_prep['diagnosis'].values.astype(np.float32).reshape(-1, 1)

# Train-test split (80% train, 20% test)
X_train_c, X_test_c, y_train_c, y_test_c = train_test_split(X_c, y_c, test_size=0.2, random_state=42)

# Standardize features
scaler_c = StandardScaler()
X_train_c_scaled = scaler_c.fit_transform(X_train_c)
X_test_c_scaled = scaler_c.transform(X_test_c)

# Convert to PyTorch tensors
X_train_c_tensor = torch.tensor(X_train_c_scaled, dtype=torch.float32)
y_train_c_tensor = torch.tensor(y_train_c, dtype=torch.float32)
X_test_c_tensor = torch.tensor(X_test_c_scaled, dtype=torch.float32)
y_test_c_tensor = torch.tensor(y_test_c, dtype=torch.float32)

print("Preprocessed Cancer training features shape:", X_train_c_tensor.shape)
print("Preprocessed Cancer training targets shape:", y_train_c_tensor.shape)

"""### 2. Classification Neural Network Model, Training, and Evaluation"""

class CancerNet(nn.Module):
    def __init__(self, input_dim):
        super(CancerNet, self).__init__()
        self.network = nn.Sequential(
            nn.Linear(input_dim, 32),
            nn.ReLU(),
            nn.Linear(32, 16),
            nn.ReLU(),
            nn.Linear(16, 1),
            nn.Sigmoid()
        )

    def forward(self, x):
        return self.network(x)

# Initialize model, loss function, and optimizer
input_dim_c = X_train_c_tensor.shape[1]
model_c = CancerNet(input_dim_c)
criterion_c = nn.BCELoss()
optimizer_c = optim.Adam(model_c.parameters(), lr=0.005)

# Hyperparameters
epochs_c = 150
batch_size_c = 32

train_losses_c = []
val_losses_c = []
train_accs_c = []
val_accs_c = []

# Training Loop
for epoch in range(epochs_c):
    model_c.train()
    permutation = torch.randperm(X_train_c_tensor.size()[0])
    epoch_loss = 0
    correct_train = 0

    for i in range(0, X_train_c_tensor.size()[0], batch_size_c):
        indices = permutation[i:i+batch_size_c]
        batch_x, batch_y = X_train_c_tensor[indices], y_train_c_tensor[indices]

        optimizer_c.zero_grad()
        outputs = model_c(batch_x)
        loss = criterion_c(outputs, batch_y)
        loss.backward()
        optimizer_c.step()

        epoch_loss += loss.item() * batch_x.size(0)
        # Calculate training binary accuracy
        preds = (outputs >= 0.5).float()
        correct_train += (preds == batch_y).sum().item()

    epoch_loss /= X_train_c_tensor.size(0)
    train_acc = correct_train / X_train_c_tensor.size(0)
    train_losses_c.append(epoch_loss)
    train_accs_c.append(train_acc)

    # Validation
    model_c.eval()
    with torch.no_grad():
        val_outputs = model_c(X_test_c_tensor)
        val_loss = criterion_c(val_outputs, y_test_c_tensor).item()
        val_preds = (val_outputs >= 0.5).float()
        val_acc = (val_preds == y_test_c_tensor).sum().item() / y_test_c_tensor.size(0)

        val_losses_c.append(val_loss)
        val_accs_c.append(val_acc)

# Plotting loss and accuracy
fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(16, 6))

# Loss graph
ax1.plot(train_losses_c, label='Train Loss')
ax1.plot(val_losses_c, label='Validation Loss')
ax1.set_xlabel('Epochs')
ax1.set_ylabel('Loss (BCE)')
ax1.set_title('Cancer Model Training & Validation Loss')
ax1.legend()
ax1.grid(True)

# Accuracy graph
ax2.plot(train_accs_c, label='Train Accuracy')
ax2.plot(val_accs_c, label='Validation Accuracy')
ax2.set_xlabel('Epochs')
ax2.set_ylabel('Accuracy')
ax2.set_title('Cancer Model Training & Validation Accuracy')
ax2.legend()
ax2.grid(True)

plt.tight_layout()
plt.show()

# Evaluate test dataset metrics
model_c.eval()
with torch.no_grad():
    final_outputs = model_c(X_test_c_tensor).numpy()
y_pred_c = (final_outputs >= 0.5).astype(int)
y_test_c_np = y_test_c_tensor.numpy().astype(int)

# Performance metrics
accuracy_c = accuracy_score(y_test_c_np, y_pred_c)
precision_c = precision_score(y_test_c_np, y_pred_c)
recall_c = recall_score(y_test_c_np, y_pred_c)
f1_c = f1_score(y_test_c_np, y_pred_c)
cm = confusion_matrix(y_test_c_np, y_pred_c)

print("\n--- Cancer Classification Performance Metrics ---")
print(f"Accuracy:  {accuracy_c:.4f}")
print(f"Precision: {precision_c:.4f}")
print(f"Recall:    {recall_c:.4f}")
print(f"F1 Score:  {f1_c:.4f}")

# Confusion matrix plotting
plt.figure(figsize=(6, 5))
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', xticklabels=['Benign', 'Malignant'], yticklabels=['Benign', 'Malignant'])
plt.xlabel('Predicted')
plt.ylabel('Actual')
plt.title('Confusion Matrix')
plt.show()

